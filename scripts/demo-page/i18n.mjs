const fill = (template, vars) => template.replace(/\{(\w+)\}/g, (m, k) => (k in vars ? String(vars[k]) : m));

/** A localized string: `{ en, es }`, Spanish falling back to English. Variables may themselves be localized. */
export function t(key, vars = {}) {
  if (!(key in dict.en)) throw new Error(`missing i18n key: ${key}`);
  const out = {};
  for (const lang of LANGS) {
    const template = dict[lang][key] ?? dict.en[key];
    const local = Object.fromEntries(Object.entries(vars).map(([k, v]) => [k, isLoc(v) ? v[lang] : v]));
    out[lang] = fill(template, local);
  }
  return out;
}

export const isLoc = (v) => v !== null && typeof v === 'object' && typeof v.en === 'string' && typeof v.es === 'string';

/** Concatenates plain strings and localized strings into one localized string. */
export function cat(...parts) {
  return Object.fromEntries(LANGS.map((lang) => [lang, parts.map((p) => (isLoc(p) ? p[lang] : String(p ?? ''))).join('')]));
}

/** Joins a list of localized strings with a separator. */
export function joinLoc(items, sep) {
  return Object.fromEntries(LANGS.map((lang) => [lang, items.map((i) => (isLoc(i) ? i[lang] : String(i))).join(sep)]));
}
